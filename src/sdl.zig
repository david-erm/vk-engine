pub const raw_init = @extern(*const fn (InitFlags) callconv(.c) bool, .{ .name = "SDL_Init" });
pub fn init(flags: InitFlags) error{Init}!void {
    const result = raw_init(flags);
    if (!result) {
        log.err("{s}", .{getError()});
        return error.Init;
    }
}

pub const raw_createWindow = @extern(*const fn (title: [*:0]const u8, w: i32, h: i32, flags: WindowFlags) callconv(.c) ?Window, .{ .name = "SDL_CreateWindow" });
pub fn createWindow(title: [*:0]const u8, w: i32, h: i32, flags: WindowFlags) error{createWindow}!Window {
    return raw_createWindow(title, w, h, flags) orelse {
        log.err("{s}", .{getError()});
        return error.createWindow;
    };
}
