pub const vulkan = struct {
    const raw_loadLibrary = @extern(*const fn (path: ?[*:0]const u8) callconv(.c) bool, .{ .name = "SDL_Vulkan_LoadLibrary" });
    pub fn loadLibrary(path: ?[*:0]const u8) error{loadLibrary}!void {
        const result = raw_loadLibrary(path);
        if (!result) {
            log.err("{s}", .{getError()});
            return error.loadLibrary;
        }
    }
    const raw_getPresentationSupport = @extern(*const fn (instance: vk.Instance, pdevice: vk.PhysicalDevice, qfamilyindex: u32) callconv(.c) bool, .{ .name = "SDL_Vulkan_GetPresentationSupport" });
    pub fn getPresentationSupport(instance: vk.Instance, pdevice: vk.PhysicalDevice, qfamilyindex: u32) error{getPresentationSupport}!void {
        const result = raw_getPresentationSupport(instance, pdevice, qfamilyindex);
        if (!result) {
            log.err("{s}", .{getError()});
            return error.getPresentationSupport;
        }
    }

    const raw_getInstanceExtensions = @extern(*const fn (*u32) callconv(.c) ?[*]const [*:0]const u8, .{ .name = "SDL_Vulkan_GetInstanceExtensions" });
    pub fn getInstanceExtensions() error{getInstanceExtensions}![]const [*:0]const u8 {
        var count: u32 = undefined;
        var ptr = raw_getInstanceExtensions(&count) orelse {
            log.err("{s}", .{getError()});
            return error.getInstanceExtensions;
        };
        return ptr[0..count];
    }
    const raw_createSurface = @extern(*const fn (window: Window, instance: vk.Instance, allocator: ?*const vk.AllocationCallbacks, surface: *vk.SurfaceKHR) callconv(.c) bool, .{ .name = "SDL_Vulkan_CreateSurface" });
    pub fn createSurface(window: Window, instance: vk.Instance, allocator: ?*const vk.AllocationCallbacks) error{createSurface}!vk.SurfaceKHR {
        var surface: vk.SurfaceKHR = undefined;
        const result = raw_createSurface(window, instance, allocator, &surface);
        if (!result) {
            log.err("{s}", .{getError()});
            return error.createSurface;
        }
        return surface;
    }
    pub const getInstanceProcAddr = @extern(*const fn () callconv(.c) vk.pfn.vkGetInstanceProcAddr, .{ .name = "SDL_Vulkan_GetVkGetInstanceProcAddr" });
};
